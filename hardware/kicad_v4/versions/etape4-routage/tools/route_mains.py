"""Etape 4a : pistes secteur. Usage : route_mains.py entree.kicad_pcb sortie.kicad_pcb
F = dessus, B = dessous. PHASE_PROT : tout en B. MT, FP : en F, sauf FP1 (B). N : B. L : F."""
import sys
import wx, pcbnew
OX, OY = 60.0, 50.0
mm = pcbnew.FromMM
b = pcbnew.LoadBoard(sys.argv[1])
NET = b.GetNetsByName()
XR, PITCH, YM = 29.35, 8.20, 36.0
CHAIN = ["72", "71", "62", "61", "52", "51", "42", "41", "32", "31", "22", "21", "12", "11"]


def T(net, layer, w, *pts):
    for (x1, y1), (x2, y2) in zip(pts, pts[1:]):
        t = pcbnew.PCB_TRACK(b)
        t.SetStart(pcbnew.VECTOR2I(mm(x1 + OX), mm(y1 + OY)))
        t.SetEnd(pcbnew.VECTOR2I(mm(x2 + OX), mm(y2 + OY)))
        t.SetLayer({"F": pcbnew.F_Cu, "B": pcbnew.B_Cu}[layer])
        t.SetWidth(mm(w))
        t.SetNet(NET[net])
        t.SetLocked(True)
        b.Add(t)


PP = "PHASE_PROT"
YB = 27.3
# entree
T("MAINS_L", "F", 1.5, (140.16, 4.9), (140.16, 13.09), (137.5, 15.75))
T("MAINS_N", "B", 1.0, (135.08, 4.9), (135.08, 8.9), (136.48, 10.3), (142.73, 10.3), (146.5, 3.5), (152.5, 3.5), (154, 5), (154, 57.75), (152, 59.75), (149, 59.75))
# bus de phase apres fusible
T(PP, "B", 1.5, (115, 15.75), (113, 17.75), (113, 18.6))
T(PP, "B", 1.0, (113, 18.6), (113, YB))
T(PP, "B", 2.0, (46.0, YB), (137.6, YB))
T(PP, "B", 1.5, (137.6, YB), (147, YB), (149, YB + 2), (149, 49))
T(PP, "B", 0.7, (46.0, YB), (42.3, YB), (33.45, 22.3), (33.4, 22.25), (33.4, 18.5), (32.9, 18), (30.82, 18))
T(PP, "B", 0.8, (33.4, 22.25), (33.4, 25.4), (32.6, 26.2), (30.82, 26.2))
T(PP, "B", 0.8, (33.4, 25.4), (33.4, 32.46), (32.26, 33.6), (31.0, 33.6), (30.1, 34.5), (29.6, 35.5), (29.35, 36))
T(PP, "B", 0.8, (37.55, 36), (37.55, 35.3), (41.6, 31.25), (41.6, 27.3), (42.3, 27.3))
for k, z in enumerate(CHAIN):
    x = round(XR + PITCH * k, 2)
    if k >= 2:
        s = x + 1.65
        T(PP, "B", 0.8, (x, YM), (x, YM - 0.7), (s, YM - 2.35), (s, YB))
        T("MT_" + z, "F", 0.8, (x + 5.08, YM), (x + 5.08, 34.4), (x + 5.75, 33.73), (x + 5.75, 32.4))
# zones 7 et 8
T("MT_72", "F", 0.8, (34.43, 36), (34.43, 34.43), (35.56, 33.3), (39.27, 33.3), (42.07, 30.5), (42.07, 22.2))
T("MT_71", "F", 0.8, (42.63, 36), (42.63, 35.08), (46.78, 30.93), (46.78, 22.2))
T("MT_81", "F", 0.8, (30.82, 31.28), (32.6, 31.28), (34.62, 29.26), (37.5, 29.26))
