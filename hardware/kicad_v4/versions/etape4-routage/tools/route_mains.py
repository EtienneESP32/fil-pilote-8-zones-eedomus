# sorties
T("FP8", "F", 1.0, (41.34, 4.9), (37.3, 4.9), (37.3, 18.9), (37.5, 19.1))
T("FP8", "F", 1.0, (37.3, 4.9), (36.19, 3.79), (33.2, 3.79))
